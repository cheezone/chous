import { describe, expect, it } from "vitest";
import { mkdirSync, mkdtempSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { tmpdir } from "node:os";
import { lintWorkspace } from "../../src/rules/lint";

async function measures(files: Record<string, string | Buffer>, links: Record<string, string> = {}) {
  const root = mkdtempSync(join(tmpdir(), "chous-measures-"));
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  for (const [path, target] of Object.entries(links)) symlinkSync(target, join(root, path));
  const result = await lintWorkspace({ root });
  return result.issues.filter((i) => i.ruleKind === "measures").map((i) => ({ verdict: i.verdict, path: i.displayPath, key: i.message.key.replace("issue.measure.", ""), params: i.message.params }));
}

const lines = (n: number, width = 20) => `${"x".repeat(width)}\n`.repeat(n);

describe("measures", () => {
  it("lists long or heavy source files once, longest first, minified ones too, never generated or vendored ones", async () => {
    const found = await measures({
      "src/a.ts": lines(1500),
      "src/b.py": lines(1200),
      "src/short.ts": lines(1000),
      "src/gen.ts": `// Code generated by protoc. DO NOT EDIT.\n${lines(3000)}`,
      "dist-like/bundle.js": lines(300, 400),
      "vendor/lib.c": lines(5000),
      "data/big.json": lines(9000),
    });
    expect(found).toEqual([
      { verdict: "review", path: "./", key: "longFiles", params: { count: 3, lines: 1000, kib: 100, files: "src/a.ts 1500 / 31 KiB, src/b.py 1200 / 25 KiB, dist-like/bundle.js 300 / 117 KiB" } },
    ]);
  });

  it("gives an agent every file, untruncated, in the details", async () => {
    const root = Object.fromEntries(Array.from({ length: 8 }, (_, i) => [`src/m${i}.ts`, lines(1001 + i)]));
    const result = await lintWorkspace({ root: (() => {
      const dir = mkdtempSync(join(tmpdir(), "chous-details-"));
      for (const [path, content] of Object.entries(root)) {
        mkdirSync(dirname(join(dir, path)), { recursive: true });
        writeFileSync(join(dir, path), content);
      }
      return dir;
    })() });
    const long = result.issues.find((i) => i.message.key === "issue.measure.longFiles")!;
    expect(String(long.message.params?.files)).toMatch(/, …$/);
    expect((long.details?.files as unknown[]).length).toBe(8);
  });

  it("finds directories laid out flat, and a crowded root", async () => {
    const flat = Object.fromEntries(Array.from({ length: 51 }, (_, i) => [`src/handlers/h${i}.go`, "package handlers\n"]));
    const root = Object.fromEntries(Array.from({ length: 31 }, (_, i) => [`note${i}.txt`, "x"]));
    const found = await measures({ ...flat, ...root });
    expect(found.map((f) => [f.key, f.params])).toEqual([
      ["flatDirs", { count: 1, limit: 50, dirs: "src/handlers/ 51" }],
      ["crowdedRoot", { count: 31, limit: 30 }],
    ]);
  });

  it("finds identical files in any language, instructions at any size, but not one file reached twice", async () => {
    const font = Buffer.alloc(8192, 7);
    const found = await measures(
      {
        "a/fonts/雅黑.woff": font,
        "b/static/雅黑.woff": font,
        "c/res/font.woff": font,
        "AGENTS.md": "Use tabs.\n",
        "CLAUDE.md": "Use tabs.\n",
        "pkg-a/LICENSE": "x".repeat(5000),
        "pkg-b/LICENSE": "x".repeat(5000),
        "real/logo.png": Buffer.alloc(9000, 1),
      },
      { "linked": "real" },
    );
    expect(found).toEqual([
      { verdict: "review", path: "./", key: "copies", params: { count: 2, groups: "3 × 8 KiB: a/fonts/雅黑.woff, b/static/雅黑.woff, c/res/font.woff; 2 × 1 KiB: AGENTS.md, CLAUDE.md" } },
    ]);
  });

  it("puts long agent instructions up for review, and smells what GitHub will not take", async () => {
    const found = await measures({ "AGENTS.md": lines(301), "docs/CLAUDE.md": lines(300), "assets/video.mp4": Buffer.alloc(50 * 1024 * 1024) });
    expect(found.map((f) => [f.verdict, f.path, f.key])).toEqual([
      ["review", "AGENTS.md", "instructions"],
      ["smell", "assets/video.mp4", "hugeFile"],
    ]);
  });
});
